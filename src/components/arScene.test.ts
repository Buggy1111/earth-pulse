import { describe, expect, it, vi } from 'vitest'
import * as THREE from 'three'
import { disposeArModel } from './arScene'

describe('Sky AR GLB disposal', () => {
  it('disposes shared geometries, materials and textures exactly once', () => {
    const geometry = new THREE.BoxGeometry()
    const texture = new THREE.Texture()
    const material = new THREE.MeshStandardMaterial({ map: texture })
    const g = vi.spyOn(geometry, 'dispose')
    const m = vi.spyOn(material, 'dispose')
    const t = vi.spyOn(texture, 'dispose')
    const root = new THREE.Group()
    root.add(new THREE.Mesh(geometry, material))
    root.add(new THREE.Mesh(geometry, material))
    disposeArModel(root)
    expect(g).toHaveBeenCalledTimes(1)
    expect(m).toHaveBeenCalledTimes(1)
    expect(t).toHaveBeenCalledTimes(1)
  })
  it('disposes multi-material meshes and shared texture slots only once', () => {
    const geometry = new THREE.BoxGeometry()
    const sharedMap = new THREE.Texture()
    const emissiveMap = new THREE.Texture()
    const first = new THREE.MeshStandardMaterial({ map: sharedMap, emissiveMap })
    const second = new THREE.MeshStandardMaterial({ map: sharedMap })
    const geometryDispose = vi.spyOn(geometry, 'dispose')
    const firstDispose = vi.spyOn(first, 'dispose')
    const secondDispose = vi.spyOn(second, 'dispose')
    const sharedDispose = vi.spyOn(sharedMap, 'dispose')
    const emissiveDispose = vi.spyOn(emissiveMap, 'dispose')
    const root = new THREE.Group()
    root.add(new THREE.Mesh(geometry, [first, second]))
    root.add(new THREE.Mesh(geometry, [second, first]))
    disposeArModel(root)
    expect(geometryDispose).toHaveBeenCalledTimes(1)
    expect(firstDispose).toHaveBeenCalledTimes(1)
    expect(secondDispose).toHaveBeenCalledTimes(1)
    expect(sharedDispose).toHaveBeenCalledTimes(1)
    expect(emissiveDispose).toHaveBeenCalledTimes(1)
  })
})
